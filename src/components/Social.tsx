export function SocialIcon({ name, size = 16 }: { name: string; size?: number }) {
  const d = ICONS[name === 'discord_profile' ? 'discord' : name]
  if (!d) return null
  return (
    <svg viewBox="0 0 24 24" width={size} height={size} aria-hidden="true" focusable="false">
      <path d={d} fill="currentColor" />
    </svg>
  )
}

/** 当前 `contact` 里已填写、并按 SOCIALS 顺序排好的渠道 */
export function activeSocials(contact: Contact) {
  const c = contact as unknown as Record<string, string>
  return SOCIALS.filter((s) => (c[s.key] || '').trim()).map((s) => ({ ...s, url: c[s.key] }))
}

/**
 * 社交渠道条 —— 首页「关注我们」与页脚共用。
 * `variant` 只影响排版密度，样式细节由 CSS 的 `.soc` / `.soc-lg` 控制。
 */
export function SocialRow({ contact, large = false }: { contact: Contact; large?: boolean }) {
  useLang()
  const list = activeSocials(contact)
  if (!list.length) return null
  return (
    <div className={large ? 'soc-row lg' : 'soc-row'}>
      {list.map((s) => (
        <a
          key={s.key}
          className="soc"
          href={s.url}
          target="_blank"
          rel="noopener noreferrer"
          style={{ '--soc': s.color } as React.CSSProperties}
          title={s.tag ? `${s.label} · ${t(s.tag)}` : s.label}
        >
          <SocialIcon name={s.key} size={large ? 18 : 15} />
          <b>{s.label}</b>
          {s.tag && <small>{t(s.tag)}</small>}
        </a>
      ))}
    </div>
  )
}
