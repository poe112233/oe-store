/**
 * 首次访问一律用英文（品牌面向海外客户）。
 * 只认用户自己切过的语言：localStorage 里有记录就沿用，否则一律返回 en。
 */
function detect(): Lang {
  try {
    const saved = localStorage.getItem(STORAGE_KEY)
    if (saved && LANGS.some((l) => l.key === saved)) return saved as Lang
  } catch {
    /* ignore */
  }
  return 'en'
}

let current: Lang = detect()
const listeners = new Set<() => void>()

export function getLang(): Lang {
  return current
}

export function setLang(lang: Lang) {
  if (lang === current) return
  current = lang
  try {
    localStorage.setItem(STORAGE_KEY, lang)
  } catch {
    /* ignore */
  }
  if (typeof document !== 'undefined') document.documentElement.lang = lang === 'zh' ? 'zh-CN' : lang
  listeners.forEach((fn) => fn())
}

/** 组件里调用即可在语言切换时自动重渲染 */
export function useLang(): Lang {
  const [, force] = useState(0)
  useEffect(() => {
    const fn = () => force((n) => n + 1)
    listeners.add(fn)
    return () => {
      listeners.delete(fn)
    }
  }, [])
  return current
}

/** 以英文原文为 key 取当前语言文案；缺失时回退英文。支持 {name} 形式插值。 */
export function t(key: string, vars?: Record<string, string | number>): string {
  const raw = current === 'en' ? key : dict[current]?.[key] ?? key
  if (!vars) return raw
  return raw.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? String(vars[k]) : m))
}

/** 三大类的本地化名称，供页头导航、面包屑、页脚复用 */
const GROUP_KEYS: Record<string, string> = { shoes: 'Shoes', watches: 'Watches', apparel: 'Apparel' }
export function groupLabel(key: string): string {
  return t(GROUP_KEYS[key] || key)
}

/**
 * 中英双语字段按当前语言决定主次。
 * 中文界面优先中文名，其他语言优先英文名；缺失时回落到另一个。
 */
export function primaryName(nameEn: string, nameZh?: string | null): string {
  if (current === 'zh') return (nameZh || '').trim() || nameEn
  return nameEn || (nameZh || '').trim()
}

export function secondaryName(nameEn: string, nameZh?: string | null): string {
  const en = (nameEn || '').trim()
  const zh = (nameZh || '').trim()
  // 中英名相同（或缺失）时不重复展示，避免卡片上出现两行一模一样的名字
  if (!en || !zh || zh === en) return ''
  return current === 'zh' ? en : zh
}

/** 首屏渲染时把 <html lang> 与首次访问的浏览器语言对齐 */
export function syncLangAttr() {
  if (typeof document !== 'undefined') document.documentElement.lang = current === 'zh' ? 'zh-CN' : current
}
